"""REPORT.md and the README results block, generated from reports/<set>.json. Never edit them by hand."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

START, END = "<!-- results:start -->", "<!-- results:end -->"
DESIGNS = ("status_quo", "agent_only", "nightly", "nightly_main", "lab")


def _ci(v: list[float], fmt: str = ".0%") -> str:
    return f"{v[0]:{fmt}} ({v[1]:{fmt}} to {v[2]:{fmt}})"


def headline(doc: dict[str, Any]) -> str:
    f, lab = doc["facts"], doc["simulation"]["lab"]
    fails = sorted({(x["check"]) for e in doc["matrix"].values() for x in e["failures"] if x.get("status", "fail") == "fail" and x["check"] != "runs"})
    return (
        f"On {f['environments']} {'held-out' if doc['set'] == 'heldout' else 'development'} environments ({f['pinned_versions']} pinned SDK versions), "
        f"{f['cells_ran']} of {f['cells']} scenario runs completed and {f['cells_crashed']} crashed; the checks failed on "
        f"{sum(1 for c in doc['cells'] if any(r['status'] == 'fail' for r in c['results']))} runs ({', '.join(fails) or 'none'}). "
        f"In the simulated ecosystem the lab cut project-days on broken traces by {_ci(lab['exposure_cut_vs_status_quo'])} against today."
    )


def matrix_table(doc: dict[str, Any]) -> str:
    rows = ["| Environment | Runs | Crashed | Failing checks |", "|---|---|---|---|"]
    for name, e in doc["matrix"].items():
        fails = [f"{x['scenario']}: {x['check']} ({x['detail'][:90]})" for x in e["failures"] if x.get("status", "fail") == "fail" or x["check"] == "runs"]
        rows.append(f"| {name} | {e['scenarios']} | {e['crashed']} | {'<br>'.join(fails) or 'none'} |")
    return "\n".join(rows)


def tables(doc: dict[str, Any]) -> str:
    out = [matrix_table(doc), ""]
    if doc["bisections"]:
        out += ["| First bad release | Package | Last good | First bad | Versions tested |", "|---|---|---|---|---|"]
        out += [f"| {b['name']} | {b['package']} | {b['last_good']} | {b['first_bad']} | {len(b['tested'])} |" for b in doc["bisections"]]
        out.append("")
    fs = doc["fault_study"]
    out += ["| Bug kind planted in real traces | Planted | Caught | Recall |", "|---|---|---|---|"]
    out += [f"| {k.replace('_', ' ')} | {v['planted']} | {v['caught']} | {v['recall']:.0%} |" for k, v in fs["kinds"].items()]
    out += [
        "",
        f"Harmless changes (reordered exports, extra HTTP spans, extra attributes, renamed spans, 3 ms clock jitter): {fs['benign_changes']}, false alarms: {fs['false_alarms']}.",
        "",
    ]
    t = doc["triage"]
    out += [
        "| Triage against maintainers' integration labels | Issues | Precision | Recall | F1 |",
        "|---|---|---|---|---|",
        f"| Triage agent | {t['agent']['issues']} | {t['agent']['micro']['precision']:.2f} | {t['agent']['micro']['recall']:.2f} | {t['agent']['micro']['f1']:.2f} |",
        f"| Any mention of the framework | {t['naive']['issues']} | {t['naive']['micro']['precision']:.2f} | {t['naive']['micro']['recall']:.2f} | {t['naive']['micro']['f1']:.2f} |",
        "",
    ]
    s = doc["simulation"]
    out += [
        "| Design | Bugs reaching users | Caught by the lab | Project-days on broken traces cut | Wrong-cost project-days cut | Median days, release to fix | Maintainer hours / week |",
        "|---|---|---|---|---|---|---|",
    ]
    for n in DESIGNS:
        d = s[n]
        cut = "–" if n == "status_quo" else _ci(d["exposure_cut_vs_status_quo"])
        ccut = "–" if n == "status_quo" else _ci(d["wrong_cost_cut_vs_status_quo"])
        out.append(
            f"| {d['label']} | {d['reached_users_share'][0]:.0%} | {d['caught_by_lab_share'][0]:.0%} | {cut} | {ccut} | {d['median_days_release_to_fix']:.1f} | {d['maintainer_hours_per_week'][0]:.1f} |"
        )
    return "\n".join(out)


def gates_table(doc: dict[str, Any]) -> str:
    rows = ["| Gate | Measured | Pass |", "|---|---|---|"]
    rows += [f"| {g['gate']} | {g['measured']} | {'yes' if g['pass'] else 'NO'} |" for g in doc["gates"]]
    return "\n".join(rows)


def block(dev: dict[str, Any], held: dict[str, Any] | None) -> str:
    parts = [START, "", "_Generated by `python -m gtc.eval.cli readme` from `reports/`. Do not edit by hand._", ""]
    for doc in (held, dev):
        if doc is None:
            continue
        ok = all(g["pass"] for g in doc["gates"])
        parts += [
            f"### {'Held-out' if doc['set'] == 'heldout' else 'Development'} run · collected {doc['collected_on']} · config `{doc['config_sha']}` · gates {'pass' if ok else 'FAIL'}",
            "",
            headline(doc),
            "",
            tables(doc),
            "",
        ]
    if held is None:
        parts += ["_The held-out run has not happened yet._", ""]
    parts.append(END)
    return "\n".join(parts)


def write_readme(readme: Path, text: str) -> None:
    old = readme.read_text()
    readme.write_text(re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: text, old, flags=re.S))


def report_md(dev: dict[str, Any], held: dict[str, Any] | None) -> str:
    out = ["# Results", "", "_Generated from `reports/`. Do not edit by hand._", ""]
    for doc in (held, dev):
        if doc is None:
            continue
        out += [f"## {doc['set']} (config `{doc['config_sha']}`)", "", headline(doc), "", tables(doc), "", gates_table(doc), ""]
        out += ["### Every failing or crashing run", ""]
        for c in doc["cells"]:
            bad = [r for r in c["results"] if r["status"] in ("fail", "warn")]
            if c["error"] or bad:
                out.append(
                    f"- **{c['env']}**, `{c['scenario']}`: " + ("crashed: " + c["error"] if c["error"] else "; ".join(f"{r['check']} {r['status']}: {r['detail']}" for r in bad))
                )
        out.append("")
    return "\n".join(out)
